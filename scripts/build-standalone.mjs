#!/usr/bin/env node
/**
 * Build "standalone" variants of every action and source.
 *
 * Pipedream rejects components that reference an app slug it has not registered
 * (`app: "pdfgate"`). Until the Pipedream team creates the app, the only way to run
 * these components in a workspace is to take the API key as a plain secret prop.
 *
 * For each component this script emits ONE self-contained file (no relative imports)
 * under dist-standalone/ in which:
 *   - the `app` prop is replaced by a secret `apiKey` string prop,
 *   - every `propDefinition: [app, "x"]` is expanded inline,
 *   - `this.app.<method>()` becomes `this.getApp().<method>()`, where `getApp()`
 *     binds the real app methods to `{ $auth: { api_key: this.apiKey } }`,
 *   - keys are prefixed `pdfgate_standalone-` and names suffixed "(Standalone)" so
 *     they never collide with the registry components later.
 *
 * Usage: node scripts/build-standalone.mjs [outDir]
 */
import {
  mkdir, readdir, readFile, rm, writeFile,
} from "node:fs/promises";
import path from "node:path";
import {
  fileURLToPath, pathToFileURL,
} from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DEFAULT_OUT_DIR = path.join(ROOT, "dist-standalone");

const HEADER = `// GENERATED by scripts/build-standalone.mjs — do not edit.
// Standalone variant for testing before the "pdfgate" app exists on Pipedream:
// the API key is a secret prop instead of a connected account.
import {
  axios, ConfigurationError,
} from "@pipedream/platform";
import {
  createHmac, timingSafeEqual,
} from "node:crypto";
`;

const API_KEY_PROP = `apiKey: {
      type: "string",
      label: "PDFGate API Key",
      description: "Your PDFGate API key. Keys starting with \`test_\` use the sandbox API (not billed); keys starting with \`live_\` use production.",
      secret: true,
    },`;

const GET_APP_METHOD = `    getApp() {
      return {
        $auth: {
          api_key: this.apiKey,
        },
        ...app.methods,
      };
    },
`;

const read = (relative) => readFile(path.join(ROOT, relative), "utf8");

const stripImports = (src) => src.replace(/^import[\s\S]*?from\s+"[^"]+";\n/gm, "");

const stripExports = (src) => src.replace(/^export (const|function) /gm, "$1 ");

const asConst = (src, name) => stripImports(src).replace(/^export default \{/m, `const ${name} = {`);

const serializeProp = (indent, name, definition) =>
  Object.entries(definition)
    .map(([
      key,
      value,
    ]) => `${indent}${key}: ${JSON.stringify(value)},\n`)
    .join("");

export function transformComponent(src, propDefinitions) {
  let out = stripImports(src);

  // 1. `app,` prop → secret apiKey prop
  if (!/^(\s+)app,\n/m.test(out)) {
    throw new Error("Component has no `app` prop to replace");
  }
  out = out.replace(/^(\s+)app,\n/m, (_, indent) => `${indent}${API_KEY_PROP}\n`);

  // 2. propDefinition: [app, "name"] → inline definition
  out = out.replace(
    /^(\s+)propDefinition: \[\n\s+app,\n\s+"(\w+)",\n\s+\],\n/gm,
    (_, indent, name) => {
      const definition = propDefinitions[name];
      if (!definition) {
        throw new Error(`Unknown propDefinition "${name}"`);
      }
      return serializeProp(indent, name, definition);
    },
  );

  // 3. this.app.x() → this.getApp().x()
  out = out.replaceAll("this.app.", "this.getApp().");

  // 4. add getApp() method
  if (/^ {2}methods: \{\n/m.test(out)) {
    out = out.replace(/^ {2}methods: \{\n/m, `  methods: {\n${GET_APP_METHOD}`);
  } else if (/^ {2}async run\(/m.test(out)) {
    out = out.replace(/^ {2}async run\(/m, `  methods: {\n${GET_APP_METHOD}  },\n  async run(`);
  } else if (/^ {2}hooks: \{\n/m.test(out)) {
    out = out.replace(/^ {2}hooks: \{\n/m, `  methods: {\n${GET_APP_METHOD}  },\n  hooks: {\n`);
  } else {
    throw new Error("Could not find a place to insert getApp()");
  }

  // 5. distinct key + name
  out = out
    .replace(/^ {2}key: "pdfgate-/m, "  key: \"pdfgate_standalone-")
    .replace(/^ {2}name: "(.*)",$/m, "  name: \"$1 (Standalone)\",");

  return out;
}

const listComponentFiles = async (dir) => {
  const entries = await readdir(path.join(ROOT, dir), {
    withFileTypes: true,
  });
  const files = [];
  for (const entry of entries) {
    if (!entry.isDirectory() || entry.name === "common") continue;
    files.push(path.join(dir, entry.name, `${entry.name}.mjs`));
  }
  return files.sort();
};

export async function buildStandalone({ outDir = DEFAULT_OUT_DIR } = {}) {
  const { default: app } = await import(pathToFileURL(path.join(ROOT, "pdfgate.app.mjs")));
  const { propDefinitions } = app;

  const shared = [
    stripExports(await read("common/constants.mjs")),
    stripExports(stripImports(await read("common/utils.mjs"))),
    asConst(await read("pdfgate.app.mjs"), "app"),
  ].join("\n");

  const webhookCommon = transformComponent(await read("sources/common/webhook.mjs"), propDefinitions)
    .replace(/^export default \{/m, "const common = {");

  await rm(outDir, {
    recursive: true,
    force: true,
  });

  const written = [];

  for (const file of await listComponentFiles("actions")) {
    const component = transformComponent(await read(file), propDefinitions);
    const target = path.join(outDir, file);
    await mkdir(path.dirname(target), {
      recursive: true,
    });
    await writeFile(target, [
      HEADER,
      shared,
      component,
    ].join("\n"));
    written.push(target);
  }

  for (const file of await listComponentFiles("sources")) {
    const sampleEmit = asConst(await read(path.join(path.dirname(file), "test-event.mjs")), "sampleEmit");
    const component = stripImports(await read(file))
      .replace(/^ {2}key: "pdfgate-/m, "  key: \"pdfgate_standalone-")
      .replace(/^ {2}name: "(.*)",$/m, "  name: \"$1 (Standalone)\",");
    const target = path.join(outDir, file);
    await mkdir(path.dirname(target), {
      recursive: true,
    });
    await writeFile(target, [
      HEADER,
      shared,
      webhookCommon,
      sampleEmit,
      component,
    ].join("\n"));
    written.push(target);
  }

  return written;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const outDir = process.argv[2]
    ? path.resolve(process.argv[2])
    : DEFAULT_OUT_DIR;
  const files = await buildStandalone({
    outDir,
  });
  console.log(`Wrote ${files.length} standalone components to ${outDir}`);
  for (const file of files) {
    console.log(`  ${path.relative(ROOT, file)}`);
  }
}
